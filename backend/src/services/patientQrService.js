/**
 * Get Patient QR Lifecycle History
 */
const getPatientQrHistory = async (poolOrClient, patientId) => {
  const identitiesRes = await poolOrClient.query(
    `SELECT i.id, i.token_version, i.status, i.is_active, i.expires_at,
            i.created_at, i.revoked_at, i.revocation_reason, i.last_used_at,
            u1.first_name AS created_by_first, u1.last_name AS created_by_last,
            u2.first_name AS revoked_by_first, u2.last_name AS revoked_by_last
     FROM patient_qr_identities i
     LEFT JOIN users u1 ON u1.id = i.created_by
     LEFT JOIN users u2 ON u2.id = i.revoked_by
     WHERE i.patient_id = $1
     ORDER BY i.created_at DESC`,
    [patientId]
  );

  const wristbandsRes = await poolOrClient.query(
    `SELECT w.id, w.wristband_barcode, w.printer_id, w.print_reason,
            w.print_type, w.replacement_reason, w.printed_at,
            u.first_name AS printed_by_first, u.last_name AS printed_by_last
     FROM patient_wristband_logs w
     LEFT JOIN users u ON u.id = w.printed_by
     WHERE w.patient_id = $1
     ORDER BY w.printed_at DESC`,
    [patientId]
  );

  const verificationsRes = await poolOrClient.query(
    `SELECT v.id, v.department, v.verification_method, v.identifiers_confirmed,
            v.status, v.notes, v.verified_at,
            u.first_name AS verified_by_first, u.last_name AS verified_by_last
     FROM patient_identity_verifications v
     LEFT JOIN users u ON u.id = v.actor_user_id
     WHERE v.patient_id = $1
     ORDER BY v.verified_at DESC
     LIMIT 20`,
    [patientId]
  );

  return {
    identities: identitiesRes.rows,
    wristbands: wristbandsRes.rows,
    verifications: verificationsRes.rows
  };
};

/**
 * QR Audit Monitoring Dashboard Aggregates (Phase 12)
 */
const getQrAuditStats = async (poolOrClient, { startDate = null, endDate = null, department = null } = {}) => {
  let whereClauses = [];
  let params = [];

  if (startDate) {
    params.push(startDate);
    whereClauses.push(`created_at >= $${params.length}`);
  }
  if (endDate) {
    params.push(endDate);
    whereClauses.push(`created_at <= $${params.length}`);
  }
  if (department) {
    params.push(department);
    whereClauses.push(`department = $${params.length}`);
  }
  const whereSql = whereClauses.length ? `WHERE ${whereClauses.join(' AND ')}` : '';

  const totalsRes = await poolOrClient.query(
    `SELECT
       COUNT(*) AS total_scans,
       COUNT(*) FILTER (WHERE action = 'scan_succeeded') AS successful_scans,
       COUNT(*) FILTER (WHERE action = 'scan_rejected') AS rejected_scans,
       COUNT(*) FILTER (WHERE action = 'replacement_issued' OR action = 'regenerated') AS replacements_count
     FROM patient_qr_audit_logs
     ${whereSql}`,
    params
  );

  const mismatchRes = await poolOrClient.query(
    `SELECT COUNT(*) AS total_mismatches,
            COUNT(*) FILTER (WHERE status = 'pending') AS pending_mismatches
     FROM patient_qr_mismatch_reports`
  );

  const activeIdentitiesRes = await poolOrClient.query(
    `SELECT
       COUNT(*) FILTER (WHERE status = 'active' AND is_active = true) AS active_identities,
       COUNT(*) FILTER (WHERE status = 'revoked') AS revoked_identities,
       COUNT(*) FILTER (WHERE status = 'replaced') AS replaced_identities
     FROM patient_qr_identities`
  );

  const departmentActivityRes = await poolOrClient.query(
    `SELECT COALESCE(department, 'General') AS department,
            COUNT(*) AS total,
            COUNT(*) FILTER (WHERE action = 'scan_succeeded') AS success,
            COUNT(*) FILTER (WHERE action = 'scan_rejected') AS rejected
     FROM patient_qr_audit_logs
     ${whereSql}
     GROUP BY COALESCE(department, 'General')
     ORDER BY total DESC
     LIMIT 10`,
    params
  );

  return {
    totals: totalsRes.rows[0],
    mismatches: mismatchRes.rows[0],
    identities: activeIdentitiesRes.rows[0],
    departmentActivity: departmentActivityRes.rows
  };
};

/**
 * Paginated Audit Event Log for Security Monitoring
 */
const getQrAuditEvents = async (poolOrClient, {
  startDate = null,
  endDate = null,
  department = null,
  action = null,
  limit = 25,
  offset = 0
} = {}) => {
  let whereClauses = [];
  let params = [];

  if (startDate) {
    params.push(startDate);
    whereClauses.push(`l.created_at >= $${params.length}`);
  }
  if (endDate) {
    params.push(endDate);
    whereClauses.push(`l.created_at <= $${params.length}`);
  }
  if (department) {
    params.push(department);
    whereClauses.push(`l.department = $${params.length}`);
  }
  if (action) {
    params.push(action);
    whereClauses.push(`l.action = $${params.length}`);
  }

  const whereSql = whereClauses.length ? `WHERE ${whereClauses.join(' AND ')}` : '';

  params.push(limit);
  const limitClause = `$${params.length}`;
  params.push(offset);
  const offsetClause = `$${params.length}`;

  const rowsRes = await poolOrClient.query(
    `SELECT l.id, l.patient_id, l.identity_id, l.actor_user_id, l.action,
            l.department, l.device_id, l.outcome, l.rejection_reason,
            l.ip_address, l.created_at,
            p.first_name AS patient_first, p.last_name AS patient_last,
            u.first_name AS actor_first, u.last_name AS actor_last, u.role AS actor_role
     FROM patient_qr_audit_logs l
     LEFT JOIN patients p ON p.id = l.patient_id
     LEFT JOIN users u ON u.id = l.actor_user_id
     ${whereSql}
     ORDER BY l.created_at DESC
     LIMIT ${limitClause} OFFSET ${offsetClause}`,
    params
  );

  const countRes = await poolOrClient.query(
    `SELECT COUNT(*) AS total FROM patient_qr_audit_logs l ${whereSql}`,
    params.slice(0, -2)
  );

  return {
    events: rowsRes.rows,
    total: parseInt(countRes.rows[0]?.total || '0', 10)
  };
};

/**
 * Register an Emergency Unidentified Patient (Phase 15)
 */
const registerEmergencyUnidentifiedPatient = async (client, {
  actorUserId,
  departmentId = 1,
  estimatedAge = null,
  gender = 'unknown',
  conditionDescription = 'Emergency trauma / unconscious patient',
  req = null
}) => {
  // 1. Generate unique temporary MRN
  const countRes = await client.query(`SELECT COUNT(*) AS count FROM patients WHERE is_unidentified = true`);
  const counter = parseInt(countRes.rows[0]?.count || '0', 10) + 1;
  const tempMrn = formatTemporaryMrn(counter);

  // 2. Insert patient record
  const patientRes = await client.query(
    `INSERT INTO patients (
      first_name, last_name, gender, blood_type, allergies,
      is_unidentified, temporary_mrn, created_at, updated_at
    ) VALUES (
      'Unidentified', 'Emergency Patient', $1, 'Unknown', 'Unknown (Emergency Trauma)',
      true, $2, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
    ) RETURNING *`,
    [gender, tempMrn]
  );
  const patient = patientRes.rows[0];

  // 3. Issue emergency active QR identity
  const rawToken = createToken();
  const tokenHashValue = hashToken(rawToken);

  const identRes = await client.query(
    `INSERT INTO patient_qr_identities (
      patient_id, token, token_hash, token_version, status, is_active, created_by, created_at, updated_at
    ) VALUES ($1, $2, $3, 'v1', 'active', true, $4, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP)
    RETURNING *`,
    [patient.id, rawToken, tokenHashValue, actorUserId]
  );
  const identity = identRes.rows[0];

  // 4. Create emergency encounter
  const year = new Date().getFullYear();
  const encNum = `ENC-${year}-EM${String(patient.id).padStart(4, '0')}`;
  const encRes = await client.query(
    `INSERT INTO patient_encounters (
      patient_id, encounter_number, encounter_type, status, priority,
      department_id, chief_complaint, created_at, updated_at
    ) VALUES ($1, $2, 'emergency', 'in_triage', 'emergency', $3, $4, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP)
    RETURNING *`,
    [patient.id, encNum, departmentId, conditionDescription]
  );
  const encounter = encRes.rows[0];

  // 5. Audit log
  await logQrAction(client, {
    patientId: patient.id,
    identityId: identity.id,
    actorUserId,
    action: 'issued',
    department: 'Emergency',
    outcome: 'emergency_issued',
    rejectionReason: `Emergency Unidentified: ${tempMrn}`,
    req
  });

  const payload = `${QR_PREFIX_V1}${rawToken}`;
  return {
    patient,
    encounter,
    identity,
    tempMrn,
    qrPayload: payload,
    qrCodeDataUrl: await buildQrDataUrl(payload)
  };
};

